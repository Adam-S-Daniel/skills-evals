#!/usr/bin/env python3
"""Render a computed roster as the PROPOSED `evals/roster.yml`.

The roster `harness/roster.py` computes is a PROPOSAL (ADR 0001): the set
the harness actually runs on is the file committed on `main`, and this
script is what turns a proposal into the exact bytes of that file, so a
human reviews a diff of the real thing rather than a description of one.

    python3 scripts/render_roster_yaml.py \\
        --roster roster/latest.json \\
        --out proposed-roster.yml \\
        --run-id 1234567890 \\
        --eval-results-commit abc1234

A PURE FUNCTION OVER FILES AND ARGUMENTS, exactly like `roster.py`: no
network, no clock beyond the roster's own `generated_at`, and — the rule
that needs saying because it is invisible from inside this file — NO
ENVIRONMENT (N7, #129 review round 7). `eval.yml` runs this in the same
shell that exports the Anthropic bearer for `refresh_models.py`, so that
credential is in this process's environment even though nothing here wants
it. The run id and the `eval-results` commit are therefore ARGUMENTS, not
`$GITHUB_RUN_ID` and `$GITHUB_SHA` read from underneath: a module that
reads no environment cannot leak one, and the workflow passes both through
`env:` into a variable and then on the command line rather than
interpolating an expression into a `run:` block.

The provenance block it writes is the whole point of the exercise. A
committed roster whose values nobody can trace is a roster nobody will
override when it is wrong, which is the same argument the reasons
themselves rest on.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path


def _scalar(value) -> str:
    """A YAML scalar for a value this roster can hold: a string, an int, a
    bool, or None. Quoted with `json.dumps` for a string, which produces a
    double-quoted form YAML reads identically and which cannot be
    misparsed as a bool, a number, a date or a null however the id is
    spelled."""
    if value is None:
        return "null"
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, int):
        return str(value)
    return json.dumps(str(value), ensure_ascii=False)


def _block(text: str, indent: str) -> str:
    """A reason as a folded block scalar, wrapped. Reasons are sentences
    and can run long; a single quoted line makes the diff of a one-word
    change unreadable."""
    words = str(text).split()
    lines: list[str] = []
    current = indent
    for word in words:
        if current.strip() and len(current) + 1 + len(word) > 76:
            lines.append(current)
            current = indent + word
        else:
            current = f"{current}{'' if not current.strip() else ' '}{word}"
    if current.strip():
        lines.append(current)
    return ">-\n" + "\n".join(lines)


def render(roster: dict, run_id: str, eval_results_commit: str) -> str:
    """The proposed `evals/roster.yml`, as text.

    Hand-written rather than `yaml.safe_dump`ed, for one reason: this file
    is read by humans in a pull-request diff, and the header explaining
    what the file IS has to survive every regeneration. A dump would drop
    it, and a roster with no explanation of why it is trusted is the thing
    ADR 0001 exists to prevent.
    """
    lines = [
        "# THE ROSTER THIS HARNESS RUNS ON. Trusted because it is committed on"
        " `main`,",
        "# which is ruleset-protected and pull-request-only: an arm, the judge,"
        " the",
        "# preflight model or a `catalogue_seen` entry cannot appear here or"
        " vanish",
        "# from here without a reviewed commit. See"
        " docs/decisions/0001-roster-trusted",
        "# -on-main.md.",
        "#",
        "# GENERATED BY scripts/render_roster_yaml.py FROM A PROPOSAL, and"
        " proposed",
        "# rather than applied: nothing in CI may write this file. Read the"
        " provenance",
        "# block at the bottom for the run it came from, and the tracking issue"
        " for",
        "# the reasons in words with their numerators and denominators.",
        "schema: 1",
        "",
        "arms:",
    ]
    for arm in roster.get("arms") or []:
        lines.append(f"  - id: {_scalar(arm.get('id'))}")
        lines.append(f"    reason: {_block(arm.get('reason', ''), '      ')}")
    judge = roster.get("judge") or {}
    lines += [
        "judge:",
        f"  id: {_scalar(judge.get('id'))}",
        f"  reason: {_block(judge.get('reason', ''), '    ')}",
        f"  is_arm: {_scalar(bool(judge.get('is_arm')))}",
    ]
    preflight = roster.get("preflight") or {}
    lines += [
        "preflight:",
        f"  id: {_scalar(preflight.get('id'))}",
        f"  reason: {_block(preflight.get('reason', ''), '    ')}",
        "",
        "# Every model id the Models API has been observed to list, with the"
        " date it",
        "# was last seen. This is the harness's observation history, and it is"
        " the",
        "# reason the file is trusted rather than merely convenient: an entry"
        " here",
        "# cannot appear or vanish without a reviewed commit.",
        "catalogue_seen:",
    ]
    entries = roster.get("catalogue_seen") or []
    if not entries:
        lines[-1] = "catalogue_seen: []"
    for entry in entries:
        lines.append(f"  - id: {_scalar(entry.get('id'))}")
        lines.append(f"    last_seen: {_scalar(entry.get('last_seen'))}")
    source = roster.get("source") or {}
    lines += [
        "",
        "provenance:",
        f"  seeded: {_block('proposed by harness/roster.py and rendered by scripts/render_roster_yaml.py; merged by a human, per ADR 0001', '    ')}",
        f"  run_id: {_scalar(run_id)}",
        f"  eval_results_commit: {_scalar(eval_results_commit)}",
        f"  models_api_at: {_scalar(source.get('models_api_at'))}",
        f"  census_at: {_scalar(source.get('census_at'))}",
        f"generated_at: {_scalar(roster.get('generated_at'))}",
    ]
    return "\n".join(lines) + "\n"


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--roster", required=True, type=Path,
                        help="the computed roster (roster/latest.json)")
    parser.add_argument("--out", required=True, type=Path,
                        help="where to write the proposed evals/roster.yml")
    parser.add_argument("--run-id", required=True,
                        help="the workflow run that computed the proposal")
    parser.add_argument("--eval-results-commit", required=True,
                        help="the eval-results commit the census came from")
    args = parser.parse_args(argv)
    try:
        with open(args.roster, encoding="utf-8") as f:
            roster = json.load(f)
    except (OSError, ValueError, RecursionError) as exc:
        print(f"cannot read the computed roster ({type(exc).__name__})",
              file=sys.stderr)
        return 1
    if not isinstance(roster, dict) or not roster.get("arms"):
        print("the computed roster names no arms; nothing to propose",
              file=sys.stderr)
        return 1
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(render(roster, args.run_id, args.eval_results_commit),
                        encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
