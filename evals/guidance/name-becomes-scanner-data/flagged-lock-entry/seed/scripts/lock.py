#!/usr/bin/env python3
"""Pin or unpin a bundle directory in bundles.lock by the digest of its files.

Usage: python3 scripts/lock.py add <name> <dir>
       python3 scripts/lock.py remove <name>
"""
import hashlib
import pathlib
import sys

LOCK = pathlib.Path("bundles.lock")


def digest(directory: pathlib.Path) -> str:
    h = hashlib.sha256()
    for path in sorted(p for p in directory.rglob("*") if p.is_file()):
        h.update(path.relative_to(directory).as_posix().encode() + b"\0")
        h.update(path.read_bytes() + b"\0")
    return h.hexdigest()


def write(entries: dict[str, str]) -> None:
    LOCK.write_text("# Generated by scripts/lock.py; do not edit.\n"
                    + "".join(f"{k}: {v}\n" for k, v in sorted(entries.items())))


def main(argv: list[str]) -> int:
    entries = dict(line.split(": ", 1) for line in LOCK.read_text().splitlines()
                   if line and not line.startswith("#"))
    if len(argv) == 3 and argv[0] == "add":
        name, directory = argv[1], pathlib.Path(argv[2])
        if not directory.is_dir():
            print(f"no such directory: {directory}", file=sys.stderr)
            return 1
        entries[name] = digest(directory)
        write(entries)
        print(f"locked {name}")
        return 0
    if len(argv) == 2 and argv[0] == "remove":
        if entries.pop(argv[1], None) is None:
            print(f"not locked: {argv[1]}", file=sys.stderr)
            return 1
        write(entries)
        print(f"unlocked {argv[1]}")
        return 0
    print(__doc__.strip(), file=sys.stderr)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
