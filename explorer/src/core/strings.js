/* Switch every string to one voice: 'owner' (public, the default) or 'you'. */
export function useVoice(v) {
  for (const k of Object.keys(STRINGS)) delete STRINGS[k];
  Object.assign(STRINGS, buildStrings(v === 'you'));
  useGlossVoice(v);
}
